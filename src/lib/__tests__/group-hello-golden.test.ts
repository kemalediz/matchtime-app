/**
 * THE SETTINGS-AWARE GROUP HELLO, RENDERED IN FULL (2026-10-12, go-live
 * slice S2). The review artefact for this copy, in the style of
 * `i18n/__tests__/copy-golden.test.ts`: every case is the whole message a
 * group would read, in English and in Turkish, committed as
 * `__snapshots__/group-hello.en.snap` and `group-hello.tr.snap`.
 *
 * It has its own snapshot files, not rows in `copy.en.snap`: several
 * slices are adding copy at once and that file's case count line would
 * conflict in every one of them. Fold these cases into copy-golden when
 * the go-live work has landed, if one artefact is preferred.
 *
 * A failure here means a byte of the hello changed. Re-record only on
 * purpose (`npx vitest run group-hello-golden -u`); the `.snap` diff is
 * what the reviewer reads.
 */
import { describe, expect, it } from "vitest";
import { DEFAULT_HELLO_SETTINGS, buildGroupHello, type GroupHelloSettings } from "../group-hello";

type L = "en" | "tr";
const MON_2100 = { day: 1, time: "21:00" };
const TUE_2000 = { day: 2, time: "20:00" };

const CASES: Array<{ id: string; patch: Partial<GroupHelloSettings>; organiser?: string | null; catchUp?: boolean }> = [
  { id: "H1 defaults, catch-up left out (equals sj_group_hello)", patch: {}, catchUp: false },
  { id: "H2 defaults", patch: {} },
  { id: "H3 defaults, no organiser name", patch: {}, organiser: null },
  { id: "H4 rolling squad, no deadline", patch: { rollingSquad: true } },
  {
    id: "H5 rolling squad, drop-out Monday 21:00, final list Tuesday 20:00, payment tracking",
    patch: { rollingSquad: true, dropOutDeadline: MON_2100, listPublish: TUE_2000, paymentTracking: true },
  },
  {
    id: "H6 the same, organisers pick",
    patch: { rollingSquad: true, dropOutDeadline: MON_2100, listPublish: TUE_2000, paymentTracking: true, organisersPick: true },
  },
  { id: "H7 rolling squad, bench off", patch: { rollingSquad: true, bench: false } },
  { id: "H8 weekly sign-up, drop-out deadline and final list", patch: { dropOutDeadline: MON_2100, listPublish: TUE_2000 } },
  { id: "H9 weekly sign-up, organisers pick", patch: { organisersPick: true } },
  { id: "H10 pay links, card and bank", patch: { payLinks: "card-and-bank" } },
  { id: "H11 pay links by card only, payment tracking", patch: { payLinks: "card", paymentTracking: true } },
  { id: "H12 pay links by bank only", patch: { payLinks: "bank" } },
  {
    id: "H13 Man of the Match and ratings only (attendance, bench, teams, reminders, stats off)",
    patch: { attendance: false, bench: false, teamBalancing: false, reminders: false, statsQa: false, squadFromList: true },
  },
  { id: "H14 Man of the Match only, no ratings", patch: { playerRating: false } },
  { id: "H15 ratings only, no Man of the Match", patch: { momVoting: false } },
  { id: "H16 squad from a pasted list, attendance on", patch: { squadFromList: true } },
  { id: "H17 monthly squad", patch: { squadMode: "monthly", paymentTracking: true, dropOutDeadline: MON_2100 } },
  { id: "H18 monthly squad, organisers pick", patch: { squadMode: "monthly", organisersPick: true } },
];

function render(lang: L): string {
  const head = `# The settings-aware group hello, language "${lang}"\n# ${CASES.length} rendered cases. Generated by group-hello-golden.test.ts; re-record only on purpose.\n`;
  return (
    head +
    CASES.map((c) => {
      const text = buildGroupHello({
        organiser: c.organiser === undefined ? "Ali" : c.organiser,
        lang,
        catchUp: c.catchUp,
        settings: { ...DEFAULT_HELLO_SETTINGS, ...c.patch },
      });
      return `\n### ${c.id}\n${text}\n`;
    }).join("")
  );
}

describe("the settings-aware group hello, pinned", () => {
  it("English", async () => {
    await expect(render("en")).toMatchFileSnapshot("./__snapshots__/group-hello.en.snap");
  });

  it("Turkish", async () => {
    await expect(render("tr")).toMatchFileSnapshot("./__snapshots__/group-hello.tr.snap");
  });

  it("no case carries an em or en dash, in either language", () => {
    expect(render("en") + render("tr")).not.toMatch(/[—–]/);
  });
});
